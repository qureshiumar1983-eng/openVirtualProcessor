// Generates the facade projects in src/Facades.
//
// A compiled SIMPL# program references Crestron's assembly names (SimplSharpPro.dll,
// Crestron.SimplSharpPro.UI.dll, ...). .NET only binds a reference to an assembly with that exact
// name, so each facade is an empty assembly with the expected name that forwards every public type
// to OpenVP.SimplSharp. Which Crestron assembly a type originally lived in doesn't matter, because
// every facade forwards every type.
//
// Usage: dotnet run --project tools/FacadeGen -- <shim.dll> <outDir> <names.txt> [shim project, relative to a facade folder]
using System.Reflection;
using System.Text;

if (args.Length < 3)
{
    Console.Error.WriteLine("usage: FacadeGen <OpenVP.SimplSharp.dll> <outDir> <names.txt>");
    return 1;
}

var shim = Assembly.LoadFrom(Path.GetFullPath(args[0]));
var outDir = Path.GetFullPath(args[1]);
var shimProject = args.Length > 3 ? args[3] : "../../OpenVP.SimplSharp/OpenVP.SimplSharp.csproj";
var names = File.ReadAllLines(args[2]).Select(l => l.Trim()).Where(l => l.Length > 0 && !l.StartsWith('#')).ToList();

var types = shim.GetExportedTypes()
    .Where(t => !t.IsNested && t.Namespace != null && !t.Namespace.StartsWith("OpenVP"))
    .OrderBy(t => t.FullName)
    .ToList();

string TypeOfName(Type t)
{
    if (!t.IsGenericTypeDefinition) return $"global::{t.FullName}";
    var baseName = t.FullName![..t.FullName!.IndexOf('`')];
    var commas = new string(',', t.GetGenericArguments().Length - 1);
    return $"global::{baseName}<{commas}>";
}

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated>Generated by tools/FacadeGen. Do not edit; rerun tools/regen-facades.sh.</auto-generated>");
foreach (var t in types)
    sb.AppendLine($"[assembly: System.Runtime.CompilerServices.TypeForwardedTo(typeof({TypeOfName(t)}))]");
Directory.CreateDirectory(outDir);
File.WriteAllText(Path.Combine(outDir, "Forwarders.g.cs"), sb.ToString());

foreach (var name in names)
{
    var dir = Path.Combine(outDir, name);
    Directory.CreateDirectory(dir);
    File.WriteAllText(Path.Combine(dir, name + ".csproj"), $"""
<Project Sdk="Microsoft.NET.Sdk">
  <!-- Generated by tools/FacadeGen. Facade named like a Crestron assembly; forwards to the clean-room implementation. -->
  <PropertyGroup>
    <AssemblyName>{name}</AssemblyName>
    <RootNamespace>OpenVP.Facades</RootNamespace>
    <ImplicitUsings>disable</ImplicitUsings>
  </PropertyGroup>
  <ItemGroup>
    <Compile Include="../Forwarders.g.cs" />
    <ProjectReference Include="{shimProject}" />
  </ItemGroup>
</Project>

""");
}

Console.WriteLine($"Forwarded {types.Count} types into {names.Count} facades.");
return 0;
