using System.Text.Json;

namespace OpenVP.Core;

/// <summary>The list entry for a recording: everything but the events.</summary>
public sealed class RecordingInfo
{
    public string Id { get; set; } = "";
    public string Name { get; set; } = "";
    public int Slot { get; set; }
    public string? Program { get; set; }
    public string? ProgramFile { get; set; }
    public string? ProgramKind { get; set; }
    public DateTimeOffset RecordedAt { get; set; }
    public long DurationMs { get; set; }
    public string EndedBy { get; set; } = "stopped";
    public RecordingCounts Counts { get; set; } = new();
    /// <summary>Result of the latest replay: null if never replayed, otherwise true (PASS) or false (FAIL).</summary>
    public bool? LastPassed { get; set; }
    public DateTimeOffset? LastReplayAt { get; set; }
}

/// <summary>
/// Recordings on disk: <c>data/recordings/slotNN/&lt;id&gt;.json</c>, with the last few replay reports of each in
/// <c>&lt;id&gt;.reports.json</c>. IDs are generated by <see cref="RecordingIds"/>; anything else is refused, so a request
/// can't reach outside the folder.
/// </summary>
public sealed class RecordingStore
{
    public const int KeepReports = 5;
    /// <summary>Largest recording file accepted on upload.</summary>
    public const long MaxFileBytes = 64L * 1024 * 1024;

    private static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web)
    {
        DefaultIgnoreCondition = System.Text.Json.Serialization.JsonIgnoreCondition.WhenWritingNull
    };
    private readonly string _root;
    private readonly object _gate = new();

    public RecordingStore(string dataDirectory) => _root = Path.Combine(dataDirectory, "recordings");

    private string SlotDir(int slot) => Path.Combine(_root, $"slot{slot:00}");
    private string? FilePath(int slot, string? id) => RecordingIds.IsValidId(id) ? Path.Combine(SlotDir(slot), id + ".json") : null;
    private string? ReportsPath(int slot, string? id) => RecordingIds.IsValidId(id) ? Path.Combine(SlotDir(slot), id + ".reports.json") : null;

    /// <summary>Saves a new recording under a new ID and returns it. The name defaults to the program and time.</summary>
    public RecordingInfo Add(int slot, Recording rec, string? name = null)
    {
        lock (_gate)
        {
            Directory.CreateDirectory(SlotDir(slot));
            string id;
            do id = RecordingIds.NewId(DateTimeOffset.UtcNow); while (File.Exists(FilePath(slot, id)!));
            rec.Id = id;
            rec.Name = string.IsNullOrWhiteSpace(name) ? (string.IsNullOrWhiteSpace(rec.Name) ? RecordingIds.DefaultName(rec.Program, rec.RecordedAt) : RecordingIds.ValidateName(rec.Name)) : RecordingIds.ValidateName(name);
            Write(FilePath(slot, id)!, RecordingJson.SerializeBytes(rec));
            return Info(rec, null);
        }
    }

    /// <summary>Reads an uploaded recording, checks it, and saves it under a new ID. Throws <see cref="RecordingFormatException"/>.</summary>
    public RecordingInfo Import(int slot, ReadOnlySpan<byte> utf8, string? name = null)
    {
        if (utf8.Length > MaxFileBytes) throw new RecordingFormatException("That file is too large to be a recording.");
        var rec = RecordingJson.Parse(utf8);
        if (string.IsNullOrWhiteSpace(rec.Name)) rec.Name = RecordingIds.DefaultName(rec.Program, rec.RecordedAt);
        else rec.Name = rec.Name.Trim().Length > RecordingIds.MaxNameLength ? rec.Name.Trim()[..RecordingIds.MaxNameLength] : rec.Name.Trim();
        if (rec.Name.Any(char.IsControl)) rec.Name = new string(rec.Name.Where(c => !char.IsControl(c)).ToArray());
        if (rec.Name.Length == 0) rec.Name = RecordingIds.DefaultName(rec.Program, rec.RecordedAt);
        return Add(slot, rec, name);
    }

    public List<RecordingInfo> List(int slot)
    {
        var list = new List<RecordingInfo>();
        lock (_gate)
        {
            if (!Directory.Exists(SlotDir(slot))) return list;
            foreach (var f in Directory.EnumerateFiles(SlotDir(slot), "*.json"))
            {
                var id = Path.GetFileNameWithoutExtension(f);
                if (!RecordingIds.IsValidId(id)) continue; // also skips <id>.reports.json
                if (Header(f) is { } info) { info.Id = id; ApplyLatest(slot, info); list.Add(info); }
            }
        }
        return list.OrderByDescending(i => i.RecordedAt).ThenByDescending(i => i.Id, StringComparer.Ordinal).ToList();
    }

    public RecordingInfo? Get(int slot, string? id)
    {
        if (FilePath(slot, id) is not { } path) return null;
        lock (_gate)
        {
            if (!File.Exists(path) || Header(path) is not { } info) return null;
            info.Id = id!;
            ApplyLatest(slot, info);
            return info;
        }
    }

    /// <summary>The whole recording, or null for an invalid or unknown ID or a file that can't be read.</summary>
    public Recording? Load(int slot, string? id)
    {
        if (FilePath(slot, id) is not { } path) return null;
        lock (_gate)
        {
            if (!File.Exists(path)) return null;
            try
            {
                var rec = RecordingJson.Parse(File.ReadAllBytes(path));
                rec.Id = id!;
                return rec;
            }
            catch (Exception e) when (e is IOException or UnauthorizedAccessException or RecordingFormatException) { return null; }
        }
    }

    /// <summary>The file's bytes as saved (for Download), or null.</summary>
    public byte[]? ReadFile(int slot, string? id)
    {
        if (FilePath(slot, id) is not { } path) return null;
        lock (_gate)
        {
            try { return File.Exists(path) ? File.ReadAllBytes(path) : null; }
            catch (Exception e) when (e is IOException or UnauthorizedAccessException) { return null; }
        }
    }

    /// <summary>Renames a recording. Returns null for an unknown ID; throws ArgumentException for a bad name.</summary>
    public RecordingInfo? Rename(int slot, string? id, string? name)
    {
        var valid = RecordingIds.ValidateName(name);
        lock (_gate)
        {
            var rec = Load(slot, id);
            if (rec == null) return null;
            rec.Name = valid;
            Write(FilePath(slot, id)!, RecordingJson.SerializeBytes(rec));
            return Get(slot, id);
        }
    }

    /// <summary>Moves the recording and its reports into <paramref name="trash"/> instead of deleting them. Null if there is no such recording.</summary>
    public TrashEntry? Delete(int slot, string? id, Trash trash)
    {
        if (FilePath(slot, id) is not { } path) return null;
        lock (_gate)
        {
            if (!File.Exists(path)) return null;
            var name = Get(slot, id)?.Name ?? "recording";
            return trash.Move("recording", $"recording \u201c{name}\u201d", slot, path, ReportsPath(slot, id)!);
        }
    }

    public bool Delete(int slot, string? id)
    {
        if (FilePath(slot, id) is not { } path) return false;
        lock (_gate)
        {
            if (!File.Exists(path)) return false;
            File.Delete(path);
            var rp = ReportsPath(slot, id)!;
            if (File.Exists(rp)) File.Delete(rp);
            return true;
        }
    }

    // ---------- replay reports ----------

    /// <summary>Keeps a report with the recording; only the last <see cref="KeepReports"/> are kept.</summary>
    public void AddReport(int slot, string? id, ReplayReport report)
    {
        if (ReportsPath(slot, id) is not { } path) return;
        lock (_gate)
        {
            if (FilePath(slot, id) is not { } rp || !File.Exists(rp)) return; // the recording was deleted meanwhile
            var list = ReadReports(path);
            list.Insert(0, report);
            if (list.Count > KeepReports) list.RemoveRange(KeepReports, list.Count - KeepReports);
            Write(path, JsonSerializer.SerializeToUtf8Bytes(list, Json));
        }
    }

    /// <summary>The recording's saved reports, newest first.</summary>
    public List<ReplayReport> Reports(int slot, string? id)
    {
        if (ReportsPath(slot, id) is not { } path) return new();
        lock (_gate) return ReadReports(path);
    }

    public ReplayReport? LatestReport(int slot, string? id) => Reports(slot, id).FirstOrDefault();

    // ---------- files ----------

    private void ApplyLatest(int slot, RecordingInfo info)
    {
        var rp = ReportsPath(slot, info.Id)!;
        if (!File.Exists(rp)) return;
        var latest = ReadReports(rp).FirstOrDefault();
        if (latest == null) return;
        info.LastPassed = latest.Passed;
        info.LastReplayAt = latest.StartedAt;
    }

    private static List<ReplayReport> ReadReports(string path)
    {
        try { return File.Exists(path) ? JsonSerializer.Deserialize<List<ReplayReport>>(File.ReadAllBytes(path), Json) ?? new() : new(); }
        catch (Exception e) when (e is IOException or JsonException or UnauthorizedAccessException) { return new(); }
    }

    private static RecordingInfo? Header(string path)
    {
        try { return JsonSerializer.Deserialize<RecordingInfo>(File.ReadAllBytes(path), Json); }
        catch (Exception e) when (e is IOException or JsonException or UnauthorizedAccessException) { return null; }
    }

    private static RecordingInfo Info(Recording r, bool? passed) => new()
    {
        Id = r.Id, Name = r.Name, Slot = r.Slot, Program = r.Program, ProgramFile = r.ProgramFile, ProgramKind = r.ProgramKind,
        RecordedAt = r.RecordedAt, DurationMs = r.DurationMs, EndedBy = r.EndedBy, Counts = r.Counts, LastPassed = passed
    };

    private static void Write(string path, byte[] bytes)
    {
        var tmp = path + ".tmp";
        File.WriteAllBytes(tmp, bytes);
        File.Move(tmp, path, true);
    }
}
